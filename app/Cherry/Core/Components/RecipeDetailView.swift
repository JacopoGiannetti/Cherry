import SwiftUI

// Dettaglio ricetta riusato ovunque (run, salvate, swap finalizzato).
struct RecipeDetailView: View {
    let title: String
    let imageUrl: String?
    let costUsd: Double
    let cookMinutes: Int
    let servings: Int
    let ingredients: [Ingredient]
    let steps: [String]
    var onSave: (() -> Void)?
    /// Quando true mostra toolbar nativa con back (es. ricette salvate).
    var showsNavigationChrome = false
    /// Ricetta già in collezione: la stella parte piena.
    var isSaved = false
    /// Link al post da cui la ricetta è arrivata: mostra "Watch the
    /// original" per rivedere il video sul social.
    var sourceUrl: String?
    /// Presente solo per le ricette importate as-is: la trasformazione
    /// che l'utente aveva rimandato resta a un tap.
    var onVeganize: (() -> Void)?
    /// Ricetta curata da Cherry: il disclaimer sta qui dentro, non
    /// sopra tutta la collezione.
    var isCherryPick = false
    /// Scritta a mano dall'utente: niente etichette "AI-generated",
    /// qui non ha generato nulla nessun modello.
    var isUserAuthored = false
    /// Dalla Collection: si può riscrivere nome, foto, ingredienti, passi.
    var onEdit: (() -> Void)? = nil
    /// Dalla Collection: la ricetta si toglie da qui, dopo conferma.
    /// Chi la passa si occupa di chiudere il dettaglio.
    var onDelete: (() -> Void)? = nil
    /// Trascritta da un post: la ricetta l'ha letta l'AI, la foto no
    /// (finché non la si rifà).
    var isImported = false
    var hasAIPhoto = true
    /// Copertina nuova al posto del fotogramma del video. Lo stato arriva
    /// dal documento della ricetta: "generating" o "failed".
    var coverStatus: String? = nil
    var coverError: String? = nil
    var onGenerateCover: (() async throws -> Void)? = nil
    /// Ricetta da un video diviso in spezzoni: apre la vista dinamica.
    var videoUrl: String? = nil
    var segments: [RecipeSegment]? = nil
    /// Ricetta da un video ma senza spezzoni: la vista dinamica si chiede
    /// a parte. Lo stato arriva dal documento: "generating" o "failed".
    var dynamicStatus: String? = nil
    var dynamicError: String? = nil
    var onGenerateDynamic: (() async throws -> Void)? = nil

    @EnvironmentObject private var appState: AppState
    @Environment(\.dismiss) private var dismiss
    @State private var showsDynamic = false
    @State private var tab: Tab = .steps
    @Namespace private var tabSpace
    /// Tra il tap e il primo aggiornamento del documento.
    @State private var dynamicRequested = false
    @State private var dynamicStartError: String?
    @State private var saved = false
    @State private var confirmingDelete = false
    /// Tra il tap e il primo aggiornamento del documento.
    @State private var coverRequested = false
    @State private var coverStartError: String?

    private var generatingCover: Bool { coverRequested || coverStatus == "generating" }

    private var aiNote: String {
        guard isImported else {
            return "This recipe, its photo and the cost estimate were generated by AI. Double-check ingredients, quantities and allergens before cooking."
        }
        let photo = hasAIPhoto ? ", its photo and the cost estimate were made" : " and the cost estimate were made"
        return "Ingredients and steps were transcribed from the original post\(photo) by AI. Double-check quantities and allergens before cooking."
    }

    private var starred: Bool { saved || isSaved }

    private var originalLink: URL? { sourceUrl.flatMap(URL.init) }

    private var sourcePlatform: String {
        let host = originalLink?.host?.lowercased() ?? ""
        if host.contains("tiktok") { return "TikTok" }
        if host.contains("instagram") { return "Instagram" }
        if host.contains("youtu") { return "YouTube" }
        if host.contains("pinterest") { return "Pinterest" }
        if host.contains("facebook") { return "Facebook" }
        return "the web"
    }

    var body: some View {
        ScrollView(showsIndicators: false) {
            VStack(alignment: .leading, spacing: 18) {
                RecipePhoto(imageUrl: imageUrl, imageStatus: imageUrl == nil ? "failed" : "ready")
                    .frame(height: 260)
                    .clipShape(RoundedRectangle(cornerRadius: 24))
                    .overlay(alignment: .bottomTrailing) {
                        if onGenerateCover != nil {
                            coverButton
                                .padding(10)
                        }
                    }

                if let message = coverStartError ?? (coverStatus == "failed" ? coverError : nil) {
                    Text(message)
                        .font(Theme.body(12, weight: .semibold))
                        .foregroundStyle(Theme.soft_red)
                }

                HStack {
                    Text(title)
                        .font(Theme.display(28))
                        .foregroundStyle(Theme.ink)
                    Spacer()
                    if let onSave {
                        Button {
                            guard !starred else { return }
                            Haptics.success()
                            saved = true
                            onSave()
                        } label: {
                            Image(systemName: starred ? "star.fill" : "star")
                                .font(.system(size: 24))
                                .foregroundStyle(starred ? Theme.amber : Theme.subtle)
                        }
                    }
                }

                // Costo e tempo li stima l'AI: una ricetta scritta a
                // mano non li ha, e "$0 · 0 min" è peggio di niente.
                HStack(spacing: 14) {
                    if costUsd > 0 {
                        Label(appState.money(costUsd), systemImage: "dollarsign.circle.fill")
                            .foregroundStyle(Theme.amber)
                    }
                    if cookMinutes > 0 {
                        Label("\(cookMinutes) min", systemImage: "clock.fill")
                            .foregroundStyle(Theme.subtle)
                    }
                    Label("\(servings) servings", systemImage: "person.2.fill")
                        .foregroundStyle(Theme.subtle)
                }
                .font(Theme.body(14, weight: .semibold))

                if isCherryPick {
                    CherryPickNotice()
                }

                actions

                if !steps.isEmpty {
                    tabPicker
                }
                if activeTab == .steps {
                    stepsList
                } else {
                    ingredientsList
                }

                if !isUserAuthored {
                    AIGeneratedNote(text: aiNote)
                }

                Spacer(minLength: 40)
            }
            .padding(20)
        }
        .background(CherryBackground(mood: .warm))
        .navigationBarTitleDisplayMode(.inline)
        .navigationBarBackButtonHidden(showsNavigationChrome)
        .toolbar { navigationToolbar }
        .alert("Delete this recipe?", isPresented: $confirmingDelete) {
            Button("Delete", role: .destructive) {
                Haptics.medium()
                onDelete?()
            }
            Button("Cancel", role: .cancel) {}
        } message: {
            Text("It leaves your collection for good. Lists you already built from it keep their items.")
        }
        .onChange(of: coverStatus) { _, status in
            if status != nil { coverRequested = false }
        }
        .onChange(of: imageUrl) { _, _ in coverRequested = false }
        .onChange(of: dynamicStatus) { _, status in
            if status != nil { dynamicRequested = false }
        }
        .onChange(of: segments) { _, _ in dynamicRequested = false }
        .fullScreenCover(isPresented: $showsDynamic) {
            if let videoUrl {
                DynamicRecipeView(
                    title: title,
                    videoUrl: videoUrl,
                    segments: segments ?? [],
                    ingredients: ingredients,
                    steps: steps,
                    onRebuild: onGenerateDynamic == nil ? nil : { requestDynamic() }
                )
            }
        }
    }

    private var dynamicStepCount: Int {
        guard videoUrl != nil else { return 0 }
        let pages = DynamicRecipeView.pages(segments, steps: steps, ingredients: ingredients)
        return pages.count >= 2 ? pages.count : 0
    }

    private var generatingDynamic: Bool { dynamicRequested || dynamicStatus == "generating" }

    private var dynamicFailure: String? {
        dynamicStartError ?? (dynamicStatus == "failed" ? (dynamicError ?? "We couldn’t build it this time.") : nil)
    }

    /// Durante una ricostruzione, o se è fallita, si vede lo stato anche
    /// quando ci sono gli spezzoni vecchi.
    private var dynamicReady: Bool { dynamicStepCount > 0 && !generatingDynamic && dynamicFailure == nil }

    /// Chi cerca la vista dinamica la trova sempre: pronta, oppure da
    /// generare a un tap.
    private var offersDynamic: Bool { dynamicReady || onGenerateDynamic != nil }

    // MARK: - Azioni

    /// Un solo gesto grande; sotto, affiancati, la vista dinamica e il post originale.
    @ViewBuilder
    private var actions: some View {
        if onVeganize != nil || originalLink != nil || offersDynamic {
            VStack(alignment: .leading, spacing: 10) {
                if let onVeganize {
                    Button {
                        Haptics.medium()
                        onVeganize()
                    } label: {
                        HStack(spacing: 8) {
                            Image(systemName: "wand.and.stars")
                                .font(.system(size: 15, weight: .semibold))
                            Text(SwapGoal.entryVerb(for: appState.tasteProfile.dietaryIdentity))
                                .font(Theme.body(16, weight: .bold))
                        }
                        .foregroundStyle(.white)
                        .frame(maxWidth: .infinity)
                        .frame(height: 50)
                        .background(Theme.brandGradient, in: .capsule)
                        .contentShape(.capsule)
                    }
                    .buttonStyle(.plain)
                }

                if offersDynamic || originalLink != nil {
                    HStack(spacing: 10) {
                        if offersDynamic { dynamicPill }
                        if let originalLink { originalPill(originalLink) }
                    }
                }

                if let dynamicFailure, !generatingDynamic {
                    Text(dynamicFailure)
                        .font(Theme.body(12, weight: .semibold))
                        .foregroundStyle(Theme.soft_red)
                        .fixedSize(horizontal: false, vertical: true)
                }
            }
        }
    }

    private var dynamicPillTitle: String {
        if dynamicReady { return "Dynamic view" }
        if generatingDynamic { return "Watching…" }
        return dynamicFailure == nil ? "Get dynamic view" : "Try again"
    }

    private var dynamicPill: some View {
        Button {
            if dynamicReady {
                Haptics.medium()
                showsDynamic = true
            } else {
                requestDynamic()
            }
        } label: {
            HStack(spacing: 8) {
                Group {
                    if generatingDynamic {
                        ProgressView()
                            .controlSize(.mini)
                            .tint(.white)
                    } else {
                        Image(systemName: dynamicReady ? "play.fill" : (dynamicFailure == nil ? "sparkles" : "arrow.clockwise"))
                            .font(.system(size: 11, weight: .bold))
                    }
                }
                .frame(width: 28, height: 28)
                .background(Circle().fill(Theme.brandGradient))

                Text(dynamicPillTitle)
                    .font(Theme.body(14, weight: .bold))
                    .lineLimit(1)
                    .minimumScaleFactor(0.8)
            }
            .foregroundStyle(.white)
            .padding(.leading, 6)
            .padding(.trailing, 14)
            .frame(maxWidth: .infinity)
            .frame(height: 46)
            .background(Theme.ink, in: .capsule)
            .contentShape(.capsule)
        }
        .buttonStyle(.plain)
        .disabled(generatingDynamic)
        .animation(Theme.Motion.quick, value: generatingDynamic)
    }

    private func originalPill(_ url: URL) -> some View {
        Link(destination: url) {
            HStack(spacing: 6) {
                Image(systemName: "play.rectangle.fill")
                    .font(.system(size: 13, weight: .semibold))
                Text(sourcePlatform == "the web" ? "Original" : sourcePlatform)
                    .font(Theme.body(14, weight: .bold))
                    .lineLimit(1)
                Image(systemName: "arrow.up.right")
                    .font(.system(size: 11, weight: .bold))
            }
            .foregroundStyle(Theme.brand)
            .frame(maxWidth: .infinity)
            .frame(height: 46)
            .contentShape(.capsule)
            .glassEffect(.regular.interactive(), in: .capsule)
        }
        .accessibilityLabel("Watch the original on \(sourcePlatform)")
    }

    // MARK: - Steps | Ingredients

    private enum Tab { case steps, ingredients }

    /// Senza passi resta solo la lista degli ingredienti, senza selettore.
    private var activeTab: Tab { steps.isEmpty ? .ingredients : tab }

    private var tabPicker: some View {
        HStack(spacing: 4) {
            tabButton("Steps", count: steps.count, .steps)
            tabButton("Ingredients", count: ingredients.count, .ingredients)
        }
        .padding(4)
        .glassEffect(.regular, in: .capsule)
    }

    private func tabButton(_ title: String, count: Int, _ value: Tab) -> some View {
        let selected = activeTab == value
        return Button {
            guard !selected else { return }
            Haptics.selection()
            withAnimation(Theme.Motion.quick) { tab = value }
        } label: {
            HStack(spacing: 6) {
                Text(title)
                Text("\(count)")
                    .opacity(0.6)
            }
            .font(Theme.body(14, weight: .bold))
            .foregroundStyle(selected ? .white : Theme.ink)
            .frame(maxWidth: .infinity)
            .frame(height: 38)
            .background {
                if selected {
                    Capsule()
                        .fill(Theme.ink)
                        .matchedGeometryEffect(id: "tab", in: tabSpace)
                }
            }
            .contentShape(.capsule)
        }
        .buttonStyle(.plain)
    }

    private var stepsList: some View {
        VStack(alignment: .leading, spacing: 14) {
            ForEach(Array(steps.enumerated()), id: \.offset) { index, step in
                HStack(alignment: .top, spacing: 12) {
                    Text("\(index + 1)")
                        .font(Theme.body(14, weight: .bold))
                        .foregroundStyle(.white)
                        .frame(width: 26, height: 26)
                        .background(Circle().fill(Theme.brand))
                    Text(step)
                        .font(Theme.body(15))
                        .foregroundStyle(Theme.ink)
                        .fixedSize(horizontal: false, vertical: true)
                }
            }
        }
        .padding(16)
        .frame(maxWidth: .infinity, alignment: .leading)
        .vegoCard()
    }

    private var ingredientsList: some View {
        // Colonna delle emoji solo se almeno uno ce l'ha: le ricette di
        // prima restano allineate come sempre.
        let hasEmoji = ingredients.contains { $0.emoji != nil }
        return VStack(spacing: 0) {
            ForEach(Array(ingredients.enumerated()), id: \.offset) { index, ingredient in
                HStack(spacing: 12) {
                    if hasEmoji {
                        Text(ingredient.emoji ?? "")
                            .font(.system(size: 20))
                            .frame(width: 28)
                    }
                    Text(ingredient.name)
                        .font(Theme.body(15, weight: .medium))
                        .foregroundStyle(Theme.ink)
                    Spacer()
                    Text(ingredient.quantity)
                        .font(Theme.body(14))
                        .foregroundStyle(Theme.subtle)
                        .multilineTextAlignment(.trailing)
                }
                .padding(.vertical, 10)
                if index < ingredients.count - 1 {
                    Divider()
                }
            }
        }
        .padding(.horizontal, 16)
        .vegoCard()
    }

    private func requestDynamic() {
        guard let onGenerateDynamic, !generatingDynamic else { return }
        Haptics.medium()
        dynamicRequested = true
        dynamicStartError = nil
        Task {
            do {
                try await onGenerateDynamic()
            } catch {
                dynamicRequested = false
                dynamicStartError = error.localizedDescription
            }
        }
    }

    /// Sulla foto, dove si guarda: rifarla è un gesto sulla foto stessa.
    private var coverButton: some View {
        Button {
            guard let onGenerateCover, !generatingCover else { return }
            Haptics.medium()
            coverRequested = true
            coverStartError = nil
            Task {
                do {
                    try await onGenerateCover()
                } catch {
                    coverRequested = false
                    coverStartError = error.localizedDescription
                }
            }
        } label: {
            HStack(spacing: 6) {
                if generatingCover {
                    ProgressView()
                        .controlSize(.mini)
                        .tint(.white)
                } else {
                    Image(systemName: "wand.and.stars")
                        .font(.system(size: 12, weight: .bold))
                }
                Text(generatingCover ? "Plating a photo…" : (hasAIPhoto ? "New photo" : "Make a cover photo"))
                    .font(Theme.body(12, weight: .bold))
            }
            .foregroundStyle(.white)
            .padding(.horizontal, 12)
            .padding(.vertical, 8)
            .background(.black.opacity(0.45), in: .capsule)
        }
        .buttonStyle(.plain)
        .disabled(generatingCover)
    }

    @ToolbarContentBuilder
    private var navigationToolbar: some ToolbarContent {
        if showsNavigationChrome {
            ToolbarItem(placement: .topBarLeading) {
                Button {
                    Haptics.light()
                    dismiss()
                } label: {
                    HStack(spacing: 4) {
                        Image(systemName: "chevron.left")
                            .font(.system(size: 16, weight: .semibold))
                        Text("Collection")
                            .font(Theme.body(16, weight: .semibold))
                    }
                    .foregroundStyle(Theme.brand)
                }
            }
        }
        // Solo "Edit" a vista: la cancellazione sta nel menu, dietro
        // una conferma. Se c'è solo il delete, il menu è tutto ciò che c'è.
        if let onEdit, onDelete == nil {
            ToolbarItem(placement: .topBarTrailing) {
                Button("Edit") {
                    Haptics.light()
                    onEdit()
                }
                .font(Theme.body(16, weight: .semibold))
                .foregroundStyle(Theme.brand)
            }
        } else if onEdit != nil || onDelete != nil {
            ToolbarItem(placement: .topBarTrailing) {
                Menu {
                    if let onEdit {
                        Button {
                            Haptics.light()
                            onEdit()
                        } label: {
                            Label("Edit recipe", systemImage: "pencil")
                        }
                    }
                    if onDelete != nil {
                        Button(role: .destructive) {
                            confirmingDelete = true
                        } label: {
                            Label("Delete recipe", systemImage: "trash")
                        }
                    }
                } label: {
                    Image(systemName: "ellipsis.circle")
                        .font(.system(size: 17, weight: .semibold))
                        .foregroundStyle(Theme.brand)
                }
                .accessibilityLabel("Recipe options")
            }
        }
    }
}
